let loadedIcons = [...FALLBACK_ICONS];
const STORAGE_KEY = 'tecxz5_material_icons_v1';

export async function fetchLiveIcons() {
  try {
    const cached = localStorage.getItem(STORAGE_KEY);
    if (cached) {
      const parsed = JSON.parse(cached);
      if (Array.isArray(parsed) && parsed.length > 50) {
        loadedIcons = parsed;
        return loadedIcons;
      }
    }
  } catch (e) {}

  try {
    const response = await fetch('https://fonts.google.com/metadata/icons');
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const text = await response.text();

    const jsonStart = text.indexOf('{');
    if (jsonStart === -1) throw new Error('Invalid JSON header');

    const data = JSON.parse(text.slice(jsonStart));
    if (data && Array.isArray(data.icons)) {
      const popular = data.icons
        .filter((icon) => typeof icon.name === 'string' && icon.name.length > 1)
        .sort((a, b) => (b.popularity || 0) - (a.popularity || 0))
        .slice(0, 500)
        .map((icon) => icon.name);

      const unique = Array.from(new Set(popular));
      if (unique.length > 50) {
        loadedIcons = unique;
        try {
          localStorage.setItem(STORAGE_KEY, JSON.stringify(unique));
        } catch (err) {}
      }
    }
  } catch (err) {
    console.warn('Google Icons API live fetch fallback:', err);
  }

  return loadedIcons;
}

export function getLoadedIcons() {
  return loadedIcons;
}

export const ICONS = loadedIcons;
